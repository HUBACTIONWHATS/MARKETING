-- Métricas diárias normalizadas (BI). dimension_key = nível + ids externos —
-- chave de idempotência da sincronização junto com metric_date.
CREATE TABLE marketing_metrics_daily (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER REFERENCES companies(id) ON DELETE SET NULL,
  provider TEXT NOT NULL,
  account_id INTEGER NOT NULL REFERENCES marketing_accounts(id) ON DELETE CASCADE,
  campaign_id INTEGER REFERENCES marketing_campaigns(id) ON DELETE CASCADE,
  ad_group_id INTEGER REFERENCES marketing_ad_groups(id) ON DELETE CASCADE,
  ad_id INTEGER REFERENCES marketing_ads(id) ON DELETE CASCADE,
  level TEXT NOT NULL CHECK (level IN ('ACCOUNT', 'CAMPAIGN', 'ADGROUP', 'AD')),
  dimension_key TEXT NOT NULL,
  metric_date TEXT NOT NULL,
  currency TEXT,
  spend_cents INTEGER NOT NULL DEFAULT 0,
  impressions INTEGER,
  reach INTEGER,
  frequency REAL,
  clicks INTEGER,
  link_clicks INTEGER,
  platform_conversations INTEGER,
  platform_leads INTEGER,
  platform_conversions REAL,
  platform_conversion_value_cents INTEGER,
  raw_metrics_json TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (dimension_key, metric_date)
);
CREATE INDEX idx_mmd_company_date ON marketing_metrics_daily(company_id, metric_date);
CREATE INDEX idx_mmd_campaign_date ON marketing_metrics_daily(campaign_id, metric_date);
CREATE INDEX idx_mmd_account_date ON marketing_metrics_daily(account_id, metric_date);
CREATE INDEX idx_mmd_provider_date ON marketing_metrics_daily(provider, metric_date);

