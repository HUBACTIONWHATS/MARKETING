-- --- Conexões OAuth (uma por "usuário da Meta/Google" que autorizou) --------
-- company_id é NULL: a conexão é da Hub Action; as CONTAS é que são vinculadas
-- a empresas (marketing_accounts.company_id). Tokens sempre cifrados.
CREATE TABLE marketing_connections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider TEXT NOT NULL CHECK (provider IN ('META', 'GOOGLE')),
  status TEXT NOT NULL DEFAULT 'CONECTADA' CHECK (status IN ('CONECTADA', 'EXPIRADA', 'ERRO', 'REVOGADA', 'RECONEXAO_NECESSARIA')),
  external_user_id TEXT,
  display_name TEXT,
  scopes TEXT,
  encrypted_access_token TEXT,
  encrypted_refresh_token TEXT,
  token_expires_at TEXT,
  last_sync_at TEXT,
  last_success_at TEXT,
  last_error_sanitized TEXT,
  created_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE marketing_accounts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  connection_id INTEGER NOT NULL REFERENCES marketing_connections(id) ON DELETE CASCADE,
  company_id INTEGER REFERENCES companies(id) ON DELETE SET NULL,
  provider TEXT NOT NULL CHECK (provider IN ('META', 'GOOGLE')),
  external_account_id TEXT NOT NULL,
  name TEXT,
  currency TEXT,
  timezone TEXT,
  account_status TEXT,
  is_manager INTEGER NOT NULL DEFAULT 0,
  login_customer_id TEXT,
  sync_enabled INTEGER NOT NULL DEFAULT 0,
  linked_at TEXT,
  last_sync_at TEXT,
  last_success_at TEXT,
  last_error_sanitized TEXT,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (provider, external_account_id)
);
CREATE INDEX idx_marketing_accounts_company ON marketing_accounts(company_id);

CREATE TABLE marketing_campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
