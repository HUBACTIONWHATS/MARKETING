-- --- Alertas (regras configuráveis + ocorrências) ---------------------------
CREATE TABLE alert_rules (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER REFERENCES companies(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  threshold REAL NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  UNIQUE (company_id, kind)
);

CREATE TABLE alerts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id INTEGER NOT NULL REFERENCES companies(id) ON DELETE CASCADE,
  category TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('CRITICO', 'ATENCAO', 'OPORTUNIDADE', 'INFORMACAO')),
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  metric TEXT,
  current_value TEXT,
  reference_value TEXT,
  status TEXT NOT NULL DEFAULT 'ABERTO' CHECK (status IN ('ABERTO', 'EM_ANALISE', 'RESOLVIDO', 'IGNORADO')),
  assignee_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  dedupe_key TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  resolved_at TEXT,
  UNIQUE (company_id, dedupe_key)
);
CREATE INDEX idx_alerts_company_status ON alerts(company_id, status, id);

-- --- Feedback de conversão (Meta CAPI / Google offline) — só arquitetura ----
